"""Generate the player's charset mapping tables as an embedded GDScript
source file (player/src/loader/charset_tables.gd).

Why embedded in code: Godot's editor filesystem scan ignores loose
binary-ish files (.b64/.bin/.dat are never registered, and even a
registered .txt copy did not survive CLI export packing — verified
2026-10-28, exported builds silently read an empty table and garbled
all text). Scripts are always packed, so the tables live in a script.

Table format: 65536 uint16-LE entries indexed by (lead<<8)|trail,
base64 of the raw 128 KiB. Entry rule (byte-verified against the
tables the player shipped with since the MVP):
  - gbk:   Python 'gb18030' codec, 2-byte strict decode, single char
           with ord <= 0xFFFF, else 0.
  - cp932: Python 'cp932' codec, same rule.
Single-byte semantics (ASCII, CP932 halfwidth katakana) live in
charset.gd, not in the tables.

Usage: python3 make_charset_tables.py
Writes ../../player/src/loader/charset_tables.gd relative to this file
(or pass an output path as argv[1]).
"""
import base64
import hashlib
import os
import sys

CHUNK = 4096  # base64 chars per array element


def build_table(codec: str) -> bytes:
    tbl = bytearray(131072)
    for lead in range(256):
        for trail in range(256):
            try:
                s = bytes([lead, trail]).decode(codec)
            except Exception:
                continue
            if len(s) == 1 and ord(s) <= 0xFFFF:
                i = ((lead << 8) | trail) * 2
                tbl[i] = ord(s) & 0xFF
                tbl[i + 1] = ord(s) >> 8
    return bytes(tbl)


def const_block(name: str, raw: bytes) -> str:
    # Emit an array of <=4 KiB literal parts; charset.gd joins them once
    # at load ("".join allocates in a single pass). Do NOT emit one
    # giant string literal or a `+` concatenation chain: the Web
    # (Emscripten) build evaluates those with quadratic COW copying and
    # dies at boot with alloc failures / "unreachable" (verified
    # 2026-10-28: stub tables boot fine, full literal chain does not).
    b64 = base64.b64encode(raw).decode("ascii")
    parts = [b64[i:i + CHUNK] for i in range(0, len(b64), CHUNK)]
    lines = ["const %s: Array[String] = [" % name]
    for p in parts:
        lines.append('\t"%s",' % p)
    lines.append("]")
    return "\n".join(lines)


def main() -> None:
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "..", "..", "player", "src", "loader", "charset_tables.gd")
    gbk = build_table("gb18030")
    cp932 = build_table("cp932")
    print("gbk   sha256:", hashlib.sha256(gbk).hexdigest())
    print("cp932 sha256:", hashlib.sha256(cp932).hexdigest())
    text = (
        "class_name CharsetTables\n"
        "extends RefCounted\n"
        "## GENERATED by reference/python/make_charset_tables.py — do not\n"
        "## edit by hand. 128 KiB uint16-LE mapping tables (base64),\n"
        "## indexed by (lead<<8)|trail; see charset.gd for semantics.\n"
        "## Embedded in code because loose data files are dropped from\n"
        "## exported .pck builds (Godot editor scan/pack quirk).\n\n"
        + const_block("GBK_PARTS", gbk)
        + "\n\n"
        + const_block("CP932_PARTS", cp932)
        + "\n\n"
        + "static func table_b64(mode: String) -> String:\n"
        + "\treturn \"\".join(CP932_PARTS) if mode == \"cp932\""
        + " else \"\".join(GBK_PARTS)\n"
    )
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", out, len(text), "chars")


if __name__ == "__main__":
    main()
